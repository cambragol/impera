#!/usr/bin/env python3
"""Audited engine defaults and complete overlay-symbol inventory, without game assets."""
import ast
import json
import re
import sys
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root / 'src/vars.c').read_text()
# Strip comments without changing line numbers, so source references remain useful.
clean = re.sub(r'/\*.*?\*/|//[^\n]*', lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]), source, flags=re.S)
def block(name):
    m = re.search(r'\b'+name+r'\s*[^;=]*=\s*\{(.*?)\};',clean,re.S)
    if not m: raise ValueError(name)
    return m[1]
def values(name):
    return [int(v,0) for v in re.findall(r'0x[\da-fA-F]+|\b\d+\b',block(name))]
def strings(name):
    return [json.loads(a) if a else None for a,b in re.findall(r'_STATIC_TEXT\([^,]+, ("(?:[^"\\]|\\.)*")\)|\b(0)\s*,?',block(name))]
# IDs are permanent schema identifiers. Bounds account for engine arithmetic/storage.
specs = [
 (1,'Equipment prices','D_3a82',48,1,10000,'price'),
 (2,'Reagent prices','D_3a32',5,8,255,'price'),
 (3,'Reagent bundle sizes','D_3a5a',5,8,99,'quantity'),
 (4,'Equipment shop stock','D_3ae2',9,8,255,'equipment'),
 (5,'Guild supply bundle prices','D_3bea',4,4,10000,'price'),
 (6,'Horse prices','D_3c30',4,1,10000,'price'),
 (7,'Location entrances — columns','D_1e8a',40,1,255,'coordinate'),
 (8,'Location entrances — rows','D_1eb2',40,1,255,'coordinate'),
]
# D_3bea column 3 is not read by SHOPPES_02ba and remains reserved/read-only.
header = ['/* Generated by scripts/generate-engine-tables.py; defaults come from vars.c. */',
          '#ifndef IMPERA_ENGINE_TABLE_DATA_H','#define IMPERA_ENGINE_TABLE_DATA_H',
          '#include <stdint.h>',
          'typedef struct U5EngineTable { unsigned id, rows, columns, maximum; const char *name, *symbol, *kind; unsigned address; const uint16_t *defaults; } U5EngineTable;']
for id,title,symbol,rows,cols,maximum,kind in specs:
    v=values(symbol)
    assert len(v)==rows*cols,(symbol,len(v))
    header.append(f'static const uint16_t U5_TableDefault{id}[] = {{'+','.join(map(str,v))+'};')
header.append('static const U5EngineTable U5_EngineTables[] = {')
for id,title,symbol,rows,cols,maximum,kind in specs:
    header.append(f'{{{id},{rows},{cols},{maximum},{json.dumps(title)},{json.dumps(symbol)},{json.dumps(kind)},0x{symbol[2:]},U5_TableDefault{id}}},')
header += ['};','#define U5_ENGINE_TABLE_COUNT 8u','#endif','']

names=['/* Generated engine names; shared authoring labels, not duplicate tables. */',
       'static const char *tableLocationNames[] = {']
for name in strings('D_1e3a'):names.append(json.dumps(name or '(unused)')+',')
names+=['};','static const char *tableReagentNames[] = {']
for name in strings('D_3c20'):names.append(json.dumps(name or '(unused)')+',')
names+=['};','static const unsigned char tableShopLocations[] = {'+','.join(map(str,values('D_23ca')))+'};',
        'static const char *tableMerchantNames[] = {']
for name in strings('D_21ca'):names.append(json.dumps(name or '')+',')
names+=['};','']

# All declared overlay symbols, with DOS storage widths rather than native pointer widths.
widths={'u8':1,'s8':1,'byte':1,'char':1,'u16':2,'s16':2,'int':2,'u32':4,'s32':4,
        'EnemyStats':8,'PairS8':2,'VideoDriverParams':32}
def integer(expr):
    tree=ast.parse(''.join(expr.split()),mode='eval')
    def calc(n):
        if isinstance(n,ast.Constant) and isinstance(n.value,int):return n.value
        if isinstance(n,ast.BinOp) and isinstance(n.op,(ast.Add,ast.Sub,ast.Mult)):
            a,b=calc(n.left),calc(n.right)
            return a+b if isinstance(n.op,ast.Add) else a-b if isinstance(n.op,ast.Sub) else a*b
        raise ValueError(expr)
    return calc(tree.body)
files={p.relative_to(root).as_posix():p.read_text(errors='replace') for p in sorted((root/'src').rglob('*.c')) if p.name!='vars.c'}
entries=[]
pattern=r'^([\w]+)(\s*\*\s*|\s+)(D_[\da-fA-F]+\w*)((?:\s*\[[^\]]+\])*)\s*='
for m in re.finditer(pattern,clean,re.M):
    type,ptr,symbol,dims=m.groups();address=int(re.match(r'D_([\da-fA-F]+)',symbol)[1],16)
    consumers=[]
    for path,text in files.items():
        hits=[text.count('\n',0,h.start())+1 for h in re.finditer(r'\b'+symbol+r'\b',text)]
        if hits:consumers.append({'file':path,'lines':hits})
    size=2 if '*' in ptr else widths.get(type)
    try:
        for dim in re.findall(r'\[([^\]]+)\]',dims):size*=integer(dim)
    except (ValueError,TypeError,SyntaxError):size=None
    known=next((s for s in specs if s[2]==symbol),None)
    if known:category='supported companion table';purpose=known[1]
    elif '*' in ptr:category='compiled rule/table';purpose='DOS near-pointer table; relocated to native pointers'
    elif symbol=='D_52ba_vdp' or symbol in {'D_5304','D_5358'}:category='obsolete DOS layout';purpose='Original video/driver parameters; native renderer uses runtime state'
    else:category='unresolved';purpose='Compiled initializer or runtime state; full semantics not exposed'
    entries.append({'symbol':symbol,'address':address,'offset':address+16,'length':size,
        'type':type+ptr.strip()+dims,'category':category,'purpose':purpose,
        'verifiedSpan':bool(known),'references':consumers,
        'sourceLine':source.count('\n',0,m.start())+1})
# Encoded strings remain a separate inventory: they are referenced through native literals.
for m in re.finditer(r'_STATIC_TEXT\((0x[\da-fA-F]+),\s*("(?:[^"\\]|\\.)*")\)',clean):
    addr=int(m[1],16)
    # Decode C octal/hex/simple escapes conservatively (not Unicode escape codecs).
    literal=m[2][1:-1]
    decoded=re.sub(r'\\(?:[0-7]{1,3}|x[0-9a-fA-F]+|.)',lambda x: chr(int(x[0][1:],8)) if re.fullmatch(r'\\[0-7]{1,3}',x[0]) else chr(int(x[0][2:],16)) if x[0].startswith('\\x') else {'\\n':'\n','\\r':'\r','\\t':'\t','\\"':'"','\\\\':'\\'}.get(x[0],x[0][1:]),literal)
    entries.append({'symbol':f'text/{addr:04x}','address':addr,'offset':addr+16,
        'length':len(decoded.encode('latin1'))+1,'type':'DOS byte string, NUL terminated',
        'category':'compiled rule/table','purpose':'Compiled encoded text; source address may belong to another overlay; not DATA.OVL configuration',
        'verifiedSpan':False,'references':[{'file':'src/vars.c','lines':[source.count('\n',0,m.start())+1]}]})
entries.append({'symbol':'Britannia chunk index','address':0x3876,'offset':0x3886,'length':256,'type':'u8[256]',
    'category':'supported data','purpose':'Physical Britannia chunks; 255 means implicit ocean',
    'verifiedSpan':True,'references':[{'file':'src/4000.c','lines':[]},{'file':'src/mod/runtime.c','lines':[]}]})
entries.sort(key=lambda e:(e['offset'],e['symbol']))
# Coverage reports gaps instead of claiming unexplained padding/code is editable data.
limit=48464
covered=[False]*limit
for e in entries:
    if e['verifiedSpan'] and e['length'] and e['offset']<limit:
        for i in range(max(0,e['offset']),min(limit,e['offset']+e['length'])):covered[i]=True
p=0;gaps=[]
while p<limit:
    if covered[p]:p+=1;continue
    start=p
    while p<limit and not covered[p]:p+=1
    gaps.append({'offset':start,'length':p-start,'category':'unresolved'})
manifest={'edition':'Original DOS overlay (48,464 bytes). Candidate offsets = decompiled address + 16-byte header; only marked spans are verified. Other editions and aliases need separate verification.',
          'runtime':'Only the chunk index is read from DATA.OVL. RULES.TBL provides versioned overrides of verified compiled defaults. No other overlay-byte change is advertised as effective.',
          'entries':entries,'unresolvedSpans':gaps}
json_text=json.dumps(manifest,indent=2,ensure_ascii=True)+'\n'
embedded='// Generated overlay inventory; split below MSVC string literal limits.\nstatic const char *overlayInventoryParts[] = {\n' + ''.join('R"IMPERA('+json_text[i:i+12000]+')IMPERA",\n' for i in range(0,len(json_text),12000)) + '};\n'
outputs={root/'src/mod/engine_tables_data.h':'\n'.join(header),root/'workshop/engine_table_names.h':'\n'.join(names),root/'docs/workshop-overlay-inventory.json':json_text,root/'workshop/overlay_inventory.h':embedded}
for path,text in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale generated file: {path.relative_to(root)}')
    else:path.write_text(text)
print(f'{len(entries)} entries; {len(gaps)} explicitly unresolved spans')
