#!/usr/bin/env python3
"""Generate vanilla Search records from the engine's canonical arrays."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
source = (root / "src/vars.c").read_text()


def array(name, declaration, length):
    match = re.search(r"\b" + name + declaration + r"\s*=\s*\{(.*?)\}", source, re.S)
    if not match:
        raise ValueError(f"Missing canonical array: {name}")
    values = [int(value, 16) for value in re.findall(r"0x[0-9a-f]+", match.group(1))]
    if len(values) != length:
        raise ValueError(f"Unexpected canonical array length: {name}")
    return values


names = ["D_3e78", "D_3eea", "D_3f5c", "D_3fce", "D_4040", "D_40b2"]
arrays = [array(name, r"\[0x72\]", 114) for name in names]
out = [
    "/* Generated by scripts/generate-discoveries.py from vars.c. */",
    "#ifndef IMPERA_DISCOVERIES_H",
    "#define IMPERA_DISCOVERIES_H",
    "static const unsigned char U5_Discoveries[113][6] = {",
]
# The Search handler uses 113 entries; the 114th array byte is not a discovery.
for index in range(113):
    out.append("    {" + ",".join(str(values[index]) for values in arrays) + "},")
equipment = array("D_413c", r"\[0x30\]", 48)
out += [
    "};",
    "static const unsigned char U5_ContentsEquipmentShapes[48] = {"
    + ",".join(map(str, equipment)) + "};",
    "#endif",
    "",
]
(root / "src/mod/discoveries.h").write_text("\n".join(out))
