#!/usr/bin/env python3
"""Snapshot the native vanilla tables for the portable type catalog."""
import pathlib,re,argparse
root=pathlib.Path(__file__).resolve().parents[1]
s=(root/'src/vars.c').read_text()
macros=(root/'src/macros.h').read_text()+'\n'+(root/'src/tiles.h').read_text()
constants={k:int(v,0) for k,v in re.findall(r'^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|[0-9]+)\s*$',macros,re.M)}
names=['D_54d4','D_54f4','D_5534','D_5544','D_6a14','D_6a86','D_13bc_enemyStats','D_153c_enemyFlags','D_159c','D_15cc','D_16d4','D_1b18']
out='/* Generated by scripts/generate-type-defaults.py from native vanilla tables. */\n'
for name in names:
    body=re.search(r'\b'+name+r'\[[^;=]*=\s*\{(.*?)\};',s,re.S).group(1)
    body=re.sub(r'//[^\n]*|/\*.*?\*/','',body,flags=re.S)
    body=re.sub(r'\b[A-Za-z_]\w*\b',lambda m:str(constants[m[0]]) if m[0] in constants else m[0],body)
    if name=='D_13bc_enemyStats':
        out+='static const unsigned char vanillaStats[48][8] = {'+body+'};\n'
    else:
        out+='static const unsigned '+('short' if name=='D_153c_enemyFlags' else 'char')+' vanilla_'+name+'[] = {'+body+'};\n'
for name in ['D_1856','D_18b6']:
    body=re.search(r'\b'+name+r'\[[^;=]*=\s*\{(.*?)\};',s,re.S).group(1)
    body=re.sub(r'_STATIC_TEXT\([^,]+,\s*("(?:\\.|[^"\\])*")\)', r'\1', body)
    body=re.sub(r'//[^\n]*', '', body)
    strings=[v.strip() if v.strip()!='0' else '""' for v in body.split(',') if v.strip()]
    assert len(strings)==48
    out+='static const char *const vanilla_'+name+'[48] = {'+','.join(strings)+'};\n'
out='\n'.join(line.rstrip() for line in out.splitlines())+'\n'
p=root/'src/mod/type_defaults.h'
a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
if args.check:
    assert p.read_text()==out, 'Regenerate type_defaults.h'
else:p.write_text(out)
