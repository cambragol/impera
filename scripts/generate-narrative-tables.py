#!/usr/bin/env python3
"""Regenerate audited narrative tables from the engine; no game assets required."""
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
s = (root / 'src/vars.c').read_text()
def values(name):
    m = re.search(r'\b' + name + r'\[[^;=]+?=\s*\{(.*?)\};', s, re.S)
    return [int(v, 0) for v in re.findall(r'0x[\da-f]+|\b\d+\b', m[1])]
def strings(name):
    m = re.search(r'\b' + name + r'\[[^;=]+?=\s*\{(.*?)\};', s, re.S)
    return re.findall(r'_STATIC_TEXT\([^,]+, ("(?:[^"\\]|\\.)*")\)|\b(0)\s*,?', m[1])
rows = []
def add(resource, offset, id, label):
    rows.append((resource, offset, id, label))
virtues = [a.strip('"') for a,b in strings('D_1f4e')]
add('QUESTION.DAT',0,'creation/introduction','Introduction')
add('QUESTION.DAT',0x322,'creation/completion','Character completed')
v=values('D_517c')
assert len(virtues)==8 and len(v)==64
assert len(strings('D_24ea'))==128
for a in range(8):
    for b in range(a+1,8):
        add('QUESTION.DAT',v[a*8+b],f'creation/{a}/{b}',f'{virtues[a]} or {virtues[b]}')
for i,o in enumerate(values('D_3dca')):
    add('END.DAT',o,f'ending/page/{i+1}',f'Ending page {i+1}')
for i,o in enumerate(values('D_1a74')+[0x29f]):
    add('KARMA.DAT',o,f'karma/speech/{i}',f'Karma {i*20}-{min(100,i*20+19)}' if i<5 else 'Lord British: karma 80-100')
services=['Weapons and armour','Tavern','Horses','Shipwright','Reagents','Guild supplies','Healer','Inn']
for table, context in [('D_3b2a','Greeting'),('D_3b6a','Refusal'),('D_3baa','Farewell')]:
    for i,o in enumerate(values(table)):
        add('SHOPPE.DAT',o,f'shop/{context.lower()}/{i}',f'{services[i//4]} - {context} {i%4+1}')
equipment=[a.strip('"') for a,b in strings('D_17f6')]
for i,o in enumerate(values('D_3c48')):
    if o:
        add('SHOPPE.DAT',o,f'shop/item/{i}',f'Equipment: {equipment[i]}')
for table,prefix in [('D_3c0a','Guild supplies: keys/gems/torches'),('D_3c10','Reagent description'),('D_3cbe','Weapons transaction')]:
    for i,o in enumerate(values(table)):
        add('SHOPPE.DAT',o,f'shop/{table}/{i}',f'{prefix} {i+1}')
for o,label in [(0x21e6,'Guild supplies: insufficient gold'),(0x2215,'Guild supplies: special offer'),(0x1643,'Horses: purchase'),(0x23ab,'Healer: insufficient gold'),(0x1f2b,'Reagents: purchase total')]:
    add('SHOPPE.DAT',o,f'shop/message/{o}',label)
for table,prefix in [('D_4c66','Tavern: provisions'),('D_4d44','Tavern: gossip'),('D_4d56','Tavern: first offer'),('D_4d5e','Tavern: next offer'),('D_4e6e','Inn: room offer')]:
    for i,o in enumerate(values(table)):
        add('SHOPPE.DAT',o,f'shop/{table}/{i}',f'{prefix} {i+1}')
# Every literal entry point in all three shop consumers; dynamic calls use tables above.
for source in ['shoppes.c','shoppes2.c','shoppes3.c']:
    code=(root/'src'/source).read_text()
    response=0
    for literal in re.findall(r'SHOPPES_017a\((0x[0-9a-f]+|[0-9]+)\)',code):
        o=int(literal,0)
        if not any(r=='SHOPPE.DAT' and offset==o for r,offset,_,_ in rows):
            prefix='Inn' if source=='shoppes3.c' else 'Tavern' if o<0x1491 else 'Shipwright'
            response+=1
            add('SHOPPE.DAT',o,f'shop/message/{o}',f'{prefix}: response {response}')
# Multiple callers share an entry. Its first semantic ID is canonical; list all contexts.
unique={}
for r,o,id,label in rows:
    if (r,o) in unique:
        unique[r,o][1]+=' / '+label
    else: unique[r,o]=[id,label]
import json
out='/* Generated by scripts/generate-narrative-tables.py from src/vars.c. */\n#ifndef IMPERA_NARRATIVE_TABLES_H\n#define IMPERA_NARRATIVE_TABLES_H\n'
out+='typedef struct U5NarrativeEntry {const char *resource; unsigned offset; const char *id; const char *label;} U5NarrativeEntry;\nstatic const U5NarrativeEntry U5NarrativeEntries[] = {\n'
for (r,o),(id,label) in unique.items():
    out+='{%s,%d,%s,%s},\n'%(json.dumps(r),o,json.dumps(id),json.dumps(label,ensure_ascii=True))
out+='};\n#define U5_NARRATIVE_COUNT (sizeof(U5NarrativeEntries)/sizeof(U5NarrativeEntries[0]))\n'
for name in ['D_5164','D_516c','D_5174','D_3dee','D_3df4','D_3dfa','D_3e00']:
    out+='static const unsigned U5'+name+'[] = {'+','.join(map(str,values(name)))+'};\n'
out+='static const char *const U5Virtues[] = {'+','.join(json.dumps(x) for x in virtues)+'};\n'
out+='static const char *const U5ShopPhrases[] = {'+','.join(a or '0' for a,b in strings('D_24ea'))+'};\n#endif\n'
import sys
path=root/'src/mod/narrative_tables.h'
if '--check' in sys.argv:
    if path.read_text()!=out: raise SystemExit('Narrative tables are stale; regenerate them')
else: path.write_text(out)
